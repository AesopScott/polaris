const GENERATED_NOTICE = 'Generated by `scripts/generate-registries.js` from `compiled/contracts/`. Do not edit this section by hand.';
const START = '<!-- generated:registries:start -->';
const END = '<!-- generated:registries:end -->';
const checkOnly = process.argv.includes('--check');

function unwrap(schema) {
  let current = schema;
  const wrappers = [];
  while (current && current._def) {
    const typeName = current._def.typeName;
    if (typeName === 'ZodOptional') {
      wrappers.push('optional');
      current = current._def.innerType;
    } else if (typeName === 'ZodNullable') {
      wrappers.push('nullable');
      current = current._def.innerType;
    } else if (typeName === 'ZodDefault') {
      wrappers.push('default');
      current = current._def.innerType;
    } else {
      break;
    }
  }
  return { schema: current, wrappers };
}

function objectShape(schema) {
  const { schema: inner } = unwrap(schema);
  if (!inner || inner._def?.typeName !== 'ZodObject') return null;
  const shape = inner._def.shape;
  return typeof shape === 'function' ? shape() : shape;
}

function enumValues(schema) {
  const { schema: inner } = unwrap(schema);
  if (!inner || inner._def?.typeName !== 'ZodEnum') return null;
  return inner._def.values;
}

function literalValue(schema) {
  const { schema: inner } = unwrap(schema);
  if (!inner || inner._def?.typeName !== 'ZodLiteral') return null;
  return inner._def.value;
}

function unionOptions(schema) {
  const { schema: inner } = unwrap(schema);
  if (!inner || inner._def?.typeName !== 'ZodUnion') return null;
  return inner._def.options;
}

function describeSchema(schema) {
  const { schema: inner, wrappers } = unwrap(schema);
  if (!inner || !inner._def) return 'unknown';

  let base;
  switch (inner._def.typeName) {
    case 'ZodString':
      base = 'string';
      break;
    case 'ZodNumber':
      base = inner._def.checks?.some((check) => check.kind === 'int') ? 'integer' : 'number';
      break;
    case 'ZodBoolean':
      base = 'boolean';
      break;
    case 'ZodUnknown':
      base = 'unknown';
      break;
    case 'ZodAny':
      base = 'any';
      break;
    case 'ZodLiteral':
      base = JSON.stringify(inner._def.value);
      break;
    case 'ZodEnum':
      base = inner._def.values.map((value) => JSON.stringify(value)).join(' | ');
      break;
    case 'ZodArray':
      {
        const item = describeSchema(inner._def.type);
        base = item.includes(' | ') ? `(${item})[]` : `${item}[]`;
      }
      break;
    case 'ZodRecord':
      base = `Record<string, ${describeSchema(inner._def.valueType)}>`;
      break;
    case 'ZodObject':
      {
        const shape = objectShape(inner);
        const literalType = shape?.type ? literalValue(shape.type) : null;
        base = literalType && literalType !== 'object' ? `${literalType} object` : 'object';
      }
      break;
    case 'ZodUnion':
      base = inner._def.options.map(describeSchema).join(' | ');
      break;
    case 'ZodDiscriminatedUnion':
      base = `discriminated union on \`${inner._def.discriminator}\``;
      break;
    default:
      base = inner._def.typeName.replace(/^Zod/, '');
      break;
  }

  if (wrappers.length === 0) return base;
  return `${base} (${wrappers.join(', ')})`;
}

function isRequired(schema) {
  return !unwrap(schema).wrappers.includes('optional');
}

function markdownTable(headers, rows) {
  return [
    `| ${headers.join(' | ')} |`,
    `| ${headers.map(() => '---').join(' | ')} |`,
    ...rows.map((row) => `| ${row.join(' | ')} |`),
  ].join('\n');
}

function objectTable(schema) {
  const shape = objectShape(schema);
  if (!shape) return '_Not an object schema._';
  const rows = Object.entries(shape).map(([name, field]) => [
    `\`${name}\``,
    describeSchema(field).replaceAll('|', '\\|'),
    isRequired(field) ? 'yes' : 'no',
  ]);
  return markdownTable(['Field', 'Schema', 'Required'], rows);
}

function discriminator(schema) {
  const shape = objectShape(schema);
  if (!shape || !shape.type) return '';
  const values = enumValues(shape.type);
  if (values) return values.map((value) => `\`${value}\``).join(', ');
  const literal = literalValue(shape.type);
  if (literal !== null) return `\`${literal}\``;
  return describeSchema(shape.type);
}

function exportedSchemas(moduleExports) {
  return Object.entries(moduleExports)
    .filter(([, value]) => value && value._def)
    .sort(([a], [b]) => a.localeCompare(b));
}

function generatedSection(content) {
  return `${START}
${GENERATED_NOTICE}

${content.trimEnd()}
${END}`;
}

function mergeGeneratedSection(existing, section, fallbackHeading) {
  if (!existing.trim()) return `${fallbackHeading}\n\n${section}\n`;

  const start = existing.indexOf(START);
  const end = existing.indexOf(END);
  if (start !== -1 && end !== -1 && end > start) {
    return `${existing.slice(0, start)}${section}${existing.slice(end + END.length)}`;
  }

  const firstRuleMatch = /\r?\n---\r?\n/.exec(existing);
  if (firstRuleMatch) {
    const insertAt = firstRuleMatch.index + firstRuleMatch[0].length;
    return `${existing.slice(0, insertAt)}\n${section}\n\n---\n${existing.slice(insertAt)}`;
  }

  const firstParagraph = existing.indexOf('\n\n');
  if (firstParagraph !== -1) {
    const insertAt = firstParagraph + 2;
    return `${existing.slice(0, insertAt)}${section}\n\n${existing.slice(insertAt)}`;
  }

  return `${existing.trimEnd()}\n\n${section}\n`;
}

function normalizeEol(value) {
  return value.replace(/\r\n/g, '\n');
}

function writeFile(relativePath, content, options = {}) {
  const target = path.join(repoRoot, relativePath);
  fs.mkdirSync(path.dirname(target), { recursive: true });
  const existing = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
  const next = options.merge
    ? mergeGeneratedSection(existing, generatedSection(content), options.heading)
    : `${options.heading ? `${options.heading}\n\n` : ''}${generatedSection(content)}\n`;

  if (normalizeEol(existing) === normalizeEol(next)) {
    console.log(`unchanged ${relativePath}`);
    return;
  }

  if (checkOnly) {
    console.error(`registry drift: ${relativePath}`);
    process.exitCode = 1;
    return;
  }

  fs.writeFileSync(target, next.endsWith('\n') ? next : `${next}\n`, 'utf8');
  console.log(`generated ${relativePath}`);
}

function renderWebsocketMessages() {
  const schemas = exportedSchemas(modules.ws);
  const summaryRows = schemas.map(([name, schema]) => [
    `\`${name}\``,
    discriminator(schema).replaceAll('|', '\\|') || describeSchema(schema).replaceAll('|', '\\|'),
  ]);
  const sections = schemas.map(([name, schema]) => `### \`${name}\`\n\n${objectTable(schema)}`).join('\n\n');
  return `## Generated Zod Message Schemas

${markdownTable(['Schema export', 'Message type'], summaryRows)}

---

${sections}
`;
}

function renderBacklogTaskFields() {
  const statusValues = enumValues(modules.backlog.BacklogStatus).map((value) => `\`${value}\``).join(', ');
  const impactValues = enumValues(modules.backlog.ImpactEnum).map((value) => `\`${value}\``).join(', ');
  return `## Generated Backlog Contract Fields

This section documents the contract shape for backlog task objects stored in \`docs/backlog.json\` and \`docs/backlog-archive.json\`.

### \`BacklogTask\`

${objectTable(modules.backlog.BacklogTask)}

### \`ProofUnit\`

${objectTable(modules.backlog.ProofUnit)}

### \`ObjectiveCriteria\`

${objectTable(modules.backlog.ObjectiveCriteria)}

### Enum Values

**BacklogStatus:** ${statusValues}

**ImpactEnum:** ${impactValues}

### File Wrapper

${objectTable(modules.backlog.BacklogFile)}
`;
}

function renderToolSchemas() {
  const toolNames = modules.tools.DIRECT_TOOL_NAMES.map((name) => `\`${name}\``).join(', ');
  const schemas = exportedSchemas(modules.tools).filter(([name]) => name !== 'DirectToolName');
  const sections = schemas.map(([name, schema]) => `## \`${name}\`\n\n${objectTable(schema)}`).join('\n\n');
  return `## Direct Tool Names

${toolNames}

---

${sections}
`;
}

function renderMcpEnvelopes() {
  const schemas = exportedSchemas(modules.mcp);
  const sections = schemas.map(([name, schema]) => `## \`${name}\`\n\n${objectTable(schema)}`).join('\n\n');
  return sections;
}

